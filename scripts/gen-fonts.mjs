// Generates the title-font catalog from installed @fontsource packages.
//
//   1. npm install @fontsource/<name>
//   2. add it to FONTS below
//   3. npm run fonts
//
// Output: src/fonts/css/<pkg>.css (one lazily loaded bundle per family) and src/fonts/catalog.ts.
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const FONTS = [
  // [family, package, category]
  ['Space Grotesk', 'space-grotesk', 'Sans'],
  ['Inter', 'inter', 'Sans'],
  ['Montserrat', 'montserrat', 'Sans'],
  ['Poppins', 'poppins', 'Sans'],
  ['Outfit', 'outfit', 'Sans'],
  ['Sora', 'sora', 'Sans'],
  ['Syne', 'syne', 'Sans'],
  ['Unbounded', 'unbounded', 'Sans'],

  ['Bebas Neue', 'bebas-neue', 'Display'],
  ['Anton', 'anton', 'Display'],
  ['Oswald', 'oswald', 'Display'],
  ['Barlow Condensed', 'barlow-condensed', 'Display'],
  ['Archivo Black', 'archivo-black', 'Display'],
  ['Bungee', 'bungee', 'Display'],
  ['Monoton', 'monoton', 'Display'],
  ['Righteous', 'righteous', 'Display'],

  ['Orbitron', 'orbitron', 'Tech'],
  ['Audiowide', 'audiowide', 'Tech'],
  ['Michroma', 'michroma', 'Tech'],
  ['Rajdhani', 'rajdhani', 'Tech'],
  ['Exo 2', 'exo-2', 'Tech'],
  ['Major Mono Display', 'major-mono-display', 'Tech'],

  ['JetBrains Mono', 'jetbrains-mono', 'Mono'],
  ['IBM Plex Mono', 'ibm-plex-mono', 'Mono'],
  ['Space Mono', 'space-mono', 'Mono'],
  ['VT323', 'vt323', 'Mono'],
  ['Press Start 2P', 'press-start-2p', 'Mono'],

  ['Playfair Display', 'playfair-display', 'Serif'],
  ['DM Serif Display', 'dm-serif-display', 'Serif'],
  ['Cormorant Garamond', 'cormorant-garamond', 'Serif'],
  ['Fraunces', 'fraunces', 'Serif'],
  ['Abril Fatface', 'abril-fatface', 'Serif'],

  ['Permanent Marker', 'permanent-marker', 'Script'],
  ['Pacifico', 'pacifico', 'Script'],
  ['Caveat', 'caveat', 'Script'],
  ['Lobster', 'lobster', 'Script'],
  ['Dancing Script', 'dancing-script', 'Script'],
];

const WEIGHTS = [300, 400, 500, 600, 700, 800, 900];

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cssDir = join(root, 'src/fonts/css');
rmSync(cssDir, { recursive: true, force: true });
mkdirSync(cssDir, { recursive: true });

const entries = [];
for (const [family, pkg, category] of FONTS) {
  const dir = join(root, 'node_modules/@fontsource', pkg);
  if (!existsSync(dir)) throw new Error(`@fontsource/${pkg} is not installed`);
  const files = new Set(readdirSync(dir));
  const weights = WEIGHTS.filter((w) => files.has(`${w}.css`));
  const italic = weights.some((w) => files.has(`${w}-italic.css`));
  const imports = weights.flatMap((w) => [
    `@import '@fontsource/${pkg}/${w}.css';`,
    ...(files.has(`${w}-italic.css`) ? [`@import '@fontsource/${pkg}/${w}-italic.css';`] : []),
  ]);
  writeFileSync(join(cssDir, `${pkg}.css`), `/* generated by scripts/gen-fonts.mjs */\n${imports.join('\n')}\n`);
  entries.push(
    `  { family: ${JSON.stringify(family)}, category: '${category}', weights: [${weights.join(', ')}], italic: ${italic}, load: () => import('./css/${pkg}.css') },`,
  );
}

writeFileSync(
  join(root, 'src/fonts/catalog.ts'),
  `// generated by scripts/gen-fonts.mjs — edit the list there, then run \`npm run fonts\`

export type FontCategory = 'Sans' | 'Display' | 'Tech' | 'Mono' | 'Serif' | 'Script';

export interface FontDef {
  family: string;
  category: FontCategory;
  /** weights with real font files (others would be synthesised) */
  weights: number[];
  italic: boolean;
  /** registers the family's @font-face rules (files download only when used) */
  load: () => Promise<unknown>;
}

export const FONT_CATALOG: FontDef[] = [
${entries.join('\n')}
];
`,
);

console.log(`fonts: ${FONTS.length} families → src/fonts/catalog.ts`);
